#!/usr/bin/env python3
"""firmware/common/errors.yaml -> firmware/common/error_codes.h and docs/manual/error_codes.md"""
import os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "firmware", "common", "errors.yaml")


def ident(code):
    return "ERR_" + re.sub(r"\W", "_", code.replace("-", "_")).upper()


def main():
    errs = yaml.safe_load(open(SRC, encoding="utf-8"))["errors"]
    ids, codes = set(), set()
    for e in errs:
        assert e["id"] not in ids and e["code"] not in codes, f"duplicate {e}"
        assert e["module"] in ("WM", "SM", "UV", "ALL")
        ids.add(e["id"]); codes.add(e["code"])
    h = ["// Generated by tools/gen_errors.py from firmware/common/errors.yaml - do not edit.",
         "#pragma once", "#include <stdint.h>", "", "enum ErrorId : uint8_t {", "  ERR_NONE = 0,"]
    h += [f"  {ident(e['code'])} = {e['id']}," for e in errs]
    h += ["};", "", "struct ErrorInfo { uint8_t id; const char* code; const char* module; };",
          "static const ErrorInfo ERROR_TABLE[] = {"]
    h += [f'  {{{ident(e["code"])}, "{e["code"]}", "{e["module"]}"}},' for e in errs]
    h += ["};", "static const unsigned ERROR_TABLE_LEN = sizeof(ERROR_TABLE) / sizeof(ERROR_TABLE[0]);", "",
          "inline const char* error_code_str(uint8_t id) {",
          '  if (id == ERR_NONE) return "";',
          "  for (unsigned i = 0; i < ERROR_TABLE_LEN; i++) if (ERROR_TABLE[i].id == id) return ERROR_TABLE[i].code;",
          '  return "E-UNKNOWN";', "}", ""]
    open(os.path.join(ROOT, "firmware", "common", "error_codes.h"), "w").write("\n".join(h))
    m = ["<!-- Generated by tools/gen_errors.py - do not edit by hand; edit firmware/common/errors.yaml -->", "",
         "# Error codes", "", "| Code | Module | Situation | Action | Source | Status |", "|---|---|---|---|---|---|"]
    for e in errs:
        m.append(f"| {e['code']} | {e['module']} | {e['situation']} | {e['action']} | {e['source']} | "
                 f"{'defined in the module plan' if e['status'] == 'plan' else 'added by the firmware (to be written into the plan)'} |")
    open(os.path.join(ROOT, "docs", "manual", "error_codes.md"), "w", encoding="utf-8").write("\n".join(m) + "\n")
    print(len(errs), "codes")


main()
