#!/usr/bin/env python3
"""electrical/nets.yaml -> firmware/common/pins_{wm,sm,uv}.h  (every net that lands on a U1 GPIO)."""
import os, re
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
nets = yaml.safe_load(open(os.path.join(ROOT, "electrical", "nets.yaml"), encoding="utf-8"))
for mod, nl in nets.items():
    out = [f"// Generated by tools/gen_pins.py from electrical/nets.yaml ({mod} main board) - do not edit.",
           "#pragma once", "#include <stdint.h>", "", f"namespace {mod.lower()}_pins {{"]
    for net, pins in nl.items():
        g = [p for p in pins if p.startswith("U1.GPIO")]
        if g:
            name = re.sub(r"\W", "_", net.replace("+", "P").replace("-", "N")).upper()
            name = name.replace("1WIRE", "ONEWIRE")
            out.append(f"constexpr uint8_t PIN_{name} = {int(g[0][7:])};")
    out.append("}")
    open(os.path.join(ROOT, "firmware", "common", f"pins_{mod.lower()}.h"), "w").write("\n".join(out) + "\n")
    print(mod, sum(1 for l in out if l.startswith("constexpr")), "pins")
